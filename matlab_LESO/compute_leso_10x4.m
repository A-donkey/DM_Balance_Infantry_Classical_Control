%% compute_leso_10x4.m
% 针对双腿耦合建模（10维状态向量，4维输入）的离散线性扩张状态观测器 (LESO) 设计
% 
% 状态向量 X (10维):
%   [X_b^h, V_b^h, phi, dphi, theta_l, dtheta_l, theta_r, dtheta_r, theta_b, dtheta_b]^T
% 控制向量 U (4维):
%   [T_{r->b}, T_{l->b}, T_{wr->r}, T_{wl->l}]^T
% 增广状态向量 X_e (14维):
%   [X; d_1; d_2; d_3; d_4]^T
%
% 控制周期: Ts = 0.001 s (1000 Hz)

clear; clc;
fprintf('====================================================\n');
fprintf('双腿耦合 10状态-4输入 轮足机器人离散LESO设计与极点配置\n');
fprintf('====================================================\n\n');

% 1. 加载系统连续状态空间矩阵
mat_file = '../matlab_stimulation_LQR/lqr_results.mat';
if ~exist(mat_file, 'file')
    error('未找到 lqr_results.mat，请检查路径！');
end
load(mat_file, 'A_num', 'B_num');

n = 10; % 状态维度
m = 4;  % 控制输入维度
p = 10; % 测量输出维度（全状态测量）
q = 4;  % 扩张扰动状态维度

% 2. 离散化 (零阶保持器 c2d, 采样时间 Ts = 1ms)
Ts = 0.001; 
[G, H] = c2d(A_num, B_num, Ts);

fprintf('✓ 系统离散化完成 (Ts = %.4f s)\n', Ts);
fprintf('  G 矩阵尺寸: %dx%d, H 矩阵尺寸: %dx%d\n\n', size(G,1), size(G,2), size(H,1), size(H,2));

% 3. 构造 14 阶离散增广系统矩阵
% X_e[k+1] = A_e * X_e[k] + B_e * u[k]
% y[k]     = C_e * X_e[k]
A_e = [G, H; zeros(q, n), eye(q)];
B_e = [H; zeros(q, m)];
C_e = [eye(p), zeros(p, q)];

% 4. 可观性检验
Obsv_mat = obsv(A_e, C_e);
rank_obsv = rank(Obsv_mat);
fprintf('增广系统可观性矩阵秩: %d (总维度: %d)\n', rank_obsv, n+q);
if rank_obsv == n+q
    fprintf('✓ 增广系统完全可观，满足极点配置条件！\n\n');
else
    error('增广系统不完全可观，无法任意配置极点！');
end

% 5. 期望闭环极点选取
sys_poles = eig(A_e);

% 状态部分 10 个极点：向原点加速配置（模长缩小，提高动态响应）
fast_factor = 0.4;
obs_poles_mod = abs(sys_poles) * fast_factor;
obs_poles_mod = max(obs_poles_mod, 0.2); % 避免极点过于靠近原点导致观测器增益过大敏感于噪声

% 扰动部分 4 个极点：配置在单位圆内实轴接近 1 的位置（平稳估计慢变扰动）
obs_poles_mod(end-q+1:end) = 0.985;

% 避免重极点导致 place 算法数值发散
for i = 1:length(obs_poles_mod)
    for j = i+1:length(obs_poles_mod)
        if abs(obs_poles_mod(i) - obs_poles_mod(j)) < 1e-4
            obs_poles_mod(j) = obs_poles_mod(j) + 1e-4 * (j - i);
        end
    end
end

fprintf('期望观测器极点列表:\n');
disp(obs_poles_mod);

% 6. 使用 place 函数计算对偶系统反馈增益
K_place = place(A_e', C_e', obs_poles_mod);
L_obs = K_place'; % 观测器增益矩阵 L_e (14 x 10)

% 7. 检验闭环误差特征值
eig_obs = eig(A_e - L_obs * C_e);
fprintf('观测器闭环特征值 (模长均应 < 1):\n');
disp(abs(eig_obs));
if all(abs(eig_obs) < 1.0)
    fprintf('✓ 闭环观测器严格渐近稳定！\n\n');
else
    warning('闭环特征值存在不稳定极点，请检查！');
end

% 8. 分解矩阵以加速单片机计算
% 创新残差 e = y[k] - x_hat[k] (10维)
% x_hat[k+1] = G * x_hat[k] + H * (u[k] + d_hat[k]) + L_x * e
% d_hat[k+1] = d_hat[k] + L_d * e
L_x = L_obs(1:n, :);    % 10 x 10 状态滤波增益
L_d = L_obs(n+1:end, :);% 4 x 10 扰动更新增益

% 9. 导出为 C 语言头文件
output_header = '../Balance_Infantry_Chassis/Controller/Inc/leso_parameters.h';
fid = fopen(output_header, 'w');
if fid == -1
    error('无法创建输出头文件: %s', output_header);
end

fprintf(fid, '/**\n');
fprintf(fid, ' * @file    leso_parameters.h\n');
fprintf(fid, ' * @brief   LESO (10-State, 4-Input) Discrete Observer Matrices\n');
fprintf(fid, ' * @note    Auto-generated by compute_leso_10x4.m\n');
fprintf(fid, ' *          Control period Ts = 0.001s (1kHz)\n');
fprintf(fid, ' */\n\n');
fprintf(fid, '#ifndef __LESO_PARAMETERS_H\n');
fprintf(fid, '#define __LESO_PARAMETERS_H\n\n');
fprintf(fid, '#define LESO_STATE_DIM      10\n');
fprintf(fid, '#define LESO_CTRL_DIM       4\n');
fprintf(fid, '#define LESO_DISTURB_DIM    4\n');
fprintf(fid, '#define LESO_TOTAL_DIM      14\n\n');

% 写入 G 矩阵 (10x10)
fprintf(fid, '// Discrete System Matrix G (10x10)\n');
fprintf(fid, 'static const float LESO_G[10][10] = {\n');
for i = 1:10
    fprintf(fid, '    {');
    for j = 1:10
        fprintf(fid, '%14.7ef', G(i,j));
        if j < 10, fprintf(fid, ', '); end
    end
    if i < 10, fprintf(fid, '},\n'); else, fprintf(fid, '}\n'); end
end
fprintf(fid, '};\n\n');

% 写入 H 矩阵 (10x4)
fprintf(fid, '// Discrete Input Matrix H (10x4)\n');
fprintf(fid, 'static const float LESO_H[10][4] = {\n');
for i = 1:10
    fprintf(fid, '    {');
    for j = 1:4
        fprintf(fid, '%14.7ef', H(i,j));
        if j < 4, fprintf(fid, ', '); end
    end
    if i < 10, fprintf(fid, '},\n'); else, fprintf(fid, '}\n'); end
end
fprintf(fid, '};\n\n');

% 写入 L_x 矩阵 (10x10)
fprintf(fid, '// State Observer Gain Matrix L_x (10x10)\n');
fprintf(fid, 'static const float LESO_Lx[10][10] = {\n');
for i = 1:10
    fprintf(fid, '    {');
    for j = 1:10
        fprintf(fid, '%14.7ef', L_x(i,j));
        if j < 10, fprintf(fid, ', '); end
    end
    if i < 10, fprintf(fid, '},\n'); else, fprintf(fid, '}\n'); end
end
fprintf(fid, '};\n\n');

% 写入 L_d 矩阵 (4x10)
fprintf(fid, '// Disturbance Observer Gain Matrix L_d (4x10)\n');
fprintf(fid, 'static const float LESO_Ld[4][10] = {\n');
for i = 1:4
    fprintf(fid, '    {');
    for j = 1:10
        fprintf(fid, '%14.7ef', L_d(i,j));
        if j < 10, fprintf(fid, ', '); end
    end
    if i < 4, fprintf(fid, '},\n'); else, fprintf(fid, '}\n'); end
end
fprintf(fid, '};\n\n');

fprintf(fid, '#endif // __LESO_PARAMETERS_H\n');
fclose(fid);

fprintf('✓ C语言参数头文件导出成功: %s\n\n', output_header);

% 保存 mat 文件
save('../matlab_LESO/leso_discrete_model.mat', ...
     'G', 'H', 'A_e', 'B_e', 'C_e', 'L_obs', 'L_x', 'L_d', 'obs_poles_mod', 'Ts');
fprintf('✓ 完整模型已保存到 leso_discrete_model.mat\n');
fprintf('====================================================\n');
